#!/usr/bin/env node
/**
 * Generate the rebuild redirect block from the migration maps.
 *
 * The redirect rules for the 2026-08 re-architecture are *generated*, never
 * hand-written. The source of truth is three CSVs in roadmap/rebuild/ plus any
 * `legacySlug` set in guides frontmatter once that collection exists. Anything
 * you want redirected has to be in the map; there is no side channel.
 *
 * Usage:
 *   node scripts/generate-redirects.mjs                 # print the full block
 *   node scripts/generate-redirects.mjs --check         # diff against _redirects.rebuild, exit 1 on drift
 *   node scripts/generate-redirects.mjs --write         # splice into public/_redirects (idempotent)
 *   node scripts/generate-redirects.mjs --write --only-live
 *                                                      # write only the rules whose target exists in dist/
 *
 * --only-live is the Phase 0 shipping mode. Most of the map points at URLs the
 * rebuild has not built yet (/guides/*, /vlog/*, /series/*, /warmachine/), and
 * a 301 to a page that does not exist is worse than the 404 it replaces. It
 * filters to rules that resolve today and reports how many were held back.
 *
 * --write splices between BEGIN/END markers at the top of public/_redirects.
 * The 496 tag rules below the markers are never touched: Netlify is
 * first-match-wins, so the rebuild rules must sit above them.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MAP_DIR = join(ROOT, 'roadmap', 'rebuild');
const REFERENCE = join(MAP_DIR, '_redirects.rebuild');
const TARGET = join(ROOT, 'public', '_redirects');
const DIST = join(ROOT, 'dist');

const BEGIN = '# BEGIN REBUILD — generated by scripts/generate-redirects.mjs. Do not edit by hand.';
const END = '# END REBUILD';

// Stamped into the header. Fixed rather than "today" so repeated runs are
// byte-stable and --check stays meaningful.
const GENERATED = '2026-08-26';

const argv = process.argv.slice(2);
const has = (flag) => argv.includes(flag);

/* ---------------------------------------------------------------- CSV ---- */

/** Minimal RFC4180 reader — the maps quote any field containing a comma. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; }
        else quoted = false;
      } else field += c;
    } else if (c === '"') {
      quoted = true;
    } else if (c === ',') {
      row.push(field); field = '';
    } else if (c === '\n') {
      row.push(field); field = '';
      if (row.some((f) => f !== '')) rows.push(row);
      row = [];
    } else if (c !== '\r') {
      field += c;
    }
  }
  row.push(field);
  if (row.some((f) => f !== '')) rows.push(row);

  const header = rows.shift();
  return rows.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));
}

function readMap(name) {
  return parseCsv(readFileSync(join(MAP_DIR, name), 'utf8'));
}

/* ------------------------------------------------------- legacySlug ----- */

/**
 * Guides carry `legacySlug` when a title rewrite made the old slug wrong. The
 * collection does not exist until Phase 1; until then this returns nothing.
 */
function legacySlugRules() {
  const dir = join(ROOT, 'src', 'content', 'guides');
  if (!existsSync(dir)) return [];

  const out = [];
  const walk = (d, prefix = '') => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const full = join(d, entry.name);
      if (entry.isDirectory()) { walk(full, `${prefix}${entry.name}/`); continue; }
      if (!/\.mdx?$/.test(entry.name)) continue;

      const body = readFileSync(full, 'utf8');
      const fm = body.match(/^---\r?\n([\s\S]*?)\r?\n---/);
      if (!fm) continue;
      const m = fm[1].match(/^legacySlug:\s*["']?(.+?)["']?\s*$/m);
      if (!m) continue;

      const slug = `${prefix}${entry.name.replace(/\.mdx?$/, '')}`;
      out.push({
        from: `/${m[1].replace(/^\/|\/$/g, '')}/`,
        to: `/guides/${slug}/`,
        source: 'legacySlug',
      });
    }
  };
  walk(dir);
  return out.sort((a, b) => a.from.localeCompare(b.from));
}

/* ------------------------------------------------------------ blocks ---- */

/** Both slash variants. Netlify treats /x and /x/ as separate explicit rules. */
function rule(from, to, forced = true) {
  const code = forced ? '301!' : '301';
  const bare = from.replace(/\/$/, '');
  const lines = [];
  if (bare !== '') lines.push(`${bare}  ${to}  ${code}`);
  lines.push(`${bare}/  ${to}  ${code}`);
  return lines;
}

const CATCH_ALLS = [
  ['/blog/*', '/guides/'],
  ['/videos/*', '/guides/'],
  ['/categories/*', '/guides/'],
  ['/category/*', '/guides/'],
  ['/blog/campaigns/*', '/series/'],
  ['/blog/characters/*', '/vlog/'],
];

function collect() {
  const posts = readMap('url-map-posts.csv').map((r) => ({ from: r.old_url, to: r.new_url, source: 'posts' }));
  const pages = readMap('url-map-pages.csv').map((r) => ({ from: r.old_url, to: r.new_url, source: 'pages' }));
  const legacy = readMap('url-map-legacy-404s.csv').map((r) => ({ from: r.old_url, to: r.new_url, source: 'legacy' }));
  return { posts, pages, legacy, guides: legacySlugRules() };
}

/**
 * Render the block. `keep` filters explicit rules; catch-alls are unforced and
 * always safe, so they ride along.
 */
function render({ posts, pages, legacy, guides }, keep = () => true) {
  const out = [
    `# ---- REBUILD REDIRECTS (generated ${GENERATED}) — prepend to public/_redirects ----`,
    '# Explicit, forced (301!) so stale dist files can never shadow. Both slash variants.',
    '',
    '# posts',
  ];

  const section = (rules) => {
    for (const r of rules.filter(keep)) out.push(...rule(r.from, r.to));
  };

  section([...posts, ...guides]);
  out.push('', '# pages / listings');
  section(pages);
  out.push('', '# legacy 404s still in Google (from GSC 16-month export)');
  section(legacy);
  out.push('', '# catch-alls (unforced, last)');
  for (const [from, to] of CATCH_ALLS) out.push(`${from}  ${to}  301`);

  return out.join('\n') + '\n';
}

/* -------------------------------------------------------------- dist ---- */

/** Does this URL path resolve to a real file in dist/? */
function existsInDist(url) {
  if (!existsSync(DIST)) return false;
  const clean = url.split(/[?#]/)[0];
  const candidates = clean.endsWith('/')
    ? [join(DIST, clean, 'index.html')]
    : [join(DIST, clean), join(DIST, clean, 'index.html'), join(DIST, `${clean}.html`)];
  return candidates.some((p) => existsSync(p) && statSync(p).isFile());
}

/* --------------------------------------------------------------- run ---- */

const maps = collect();
const full = render(maps);

if (has('--check')) {
  const reference = readFileSync(REFERENCE, 'utf8');
  if (full === reference) {
    console.log(`✓ generator output is byte-identical to ${REFERENCE.replace(ROOT + '/', '')}`);
    process.exit(0);
  }
  const a = reference.split('\n');
  const b = full.split('\n');
  console.error('✗ generator output differs from the reference block.');
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) {
      console.error(`  first difference at line ${i + 1}`);
      console.error(`    reference: ${a[i] ?? '(eof)'}`);
      console.error(`    generated: ${b[i] ?? '(eof)'}`);
      break;
    }
  }
  console.error(`  reference ${a.length} lines, generated ${b.length} lines`);
  process.exit(1);
}

if (has('--write')) {
  const all = [...maps.posts, ...maps.guides, ...maps.pages, ...maps.legacy];
  let block = full;

  if (has('--only-live')) {
    const resolves = new Map();
    for (const r of all) {
      if (!resolves.has(r.to)) resolves.set(r.to, existsInDist(r.to));
    }
    const liveFroms = new Set(all.filter((r) => resolves.get(r.to)).map((r) => r.from));
    block = render(maps, (r) => liveFroms.has(r.from));

    const heldRules = all.filter((r) => !liveFroms.has(r.from));
    console.log(`--only-live: ${all.length - heldRules.length} rules shipped, ${heldRules.length} held back.`);
    const byTarget = new Map();
    for (const r of heldRules) byTarget.set(r.to, (byTarget.get(r.to) ?? 0) + 1);
    console.log('  held back, by missing target:');
    for (const [to, n] of [...byTarget].sort((x, y) => y[1] - x[1])) {
      console.log(`    ${String(n).padStart(4)}  ${to}`);
    }
  }

  const existing = readFileSync(TARGET, 'utf8');
  const stripped = existing.includes(BEGIN)
    ? existing.slice(0, existing.indexOf(BEGIN)) + existing.slice(existing.indexOf(END) + END.length + 1).replace(/^\n+/, '')
    : existing;

  writeFileSync(TARGET, `${BEGIN}\n${block}${END}\n\n${stripped.replace(/^\n+/, '')}`);
  console.log(`✓ wrote the rebuild block into ${TARGET.replace(ROOT + '/', '')}`);
  process.exit(0);
}

process.stdout.write(full);
